#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_round_trip_in_order() {
        for w in Class::ALL.windows(2) {
            assert!(w[0].name() < w[1].name());
        }
        for &c in Class::ALL {
            assert_eq!(Class::from_name(c.name()), Some(c));
        }
        assert_eq!(Class::from_name("NoSuchBlock"), None);
    }
}
