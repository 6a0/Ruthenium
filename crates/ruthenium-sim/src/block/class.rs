    /// The class with this simple name, if a block of this version is one.
    pub fn from_name(name: &str) -> Option<Class> {
        Class::ALL
            .binary_search_by(|c| c.name().cmp(name))
            .ok()
            .map(|i| Class::ALL[i])
    }
